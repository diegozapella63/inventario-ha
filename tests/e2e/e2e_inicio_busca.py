"""Início (etiqueta, destaques, busca, cômodos, categorias) e Buscar (acentos, filtros, ordem, sem resultado), no celular e no computador."""
from e2e_lib import OVERFLOW, main


async def body(r, p):
    r.start(search=False)
    d = r.data()
    total = sum(i["value"] for i in d["items"])
    b = await r.browser(p)

    for size, scheme, accent in (("cel", "dark", "amarelo"), ("estreito", "light", "coral"), ("tablet", "dark", "verde"), ("pc", "light", "azul")):
        ctx, pg = await r.page(b, size, scheme, accent)
        await r.open(pg, "#/", ".tag-value")
        val = (await pg.text_content(".tag-value")).replace("\xa0", "").replace(" ", "")
        r.eq(val, "R$" + f"{round(total):,}".replace(",", "."), f"[{size}] etiqueta com o total da casa")
        sub = await pg.text_content(".tag-sub")
        r.eq(sub, "38 itens em 6 cômodos", f"[{size}] itens e cômodos")
        facts = await pg.evaluate("[...document.querySelectorAll('.facts dt')].map(e => e.textContent.trim())")
        r.eq(facts, ["Mais valioso", "Maior cômodo", "Último cadastro", "Fotos"], f"[{size}] destaques")
        r.check(await pg.evaluate("document.querySelectorAll('.facts .sec-ic').length") == 4, f"[{size}] destaques com ícone")
        pos = await pg.evaluate("[document.querySelector('.homesearch').getBoundingClientRect().bottom, document.querySelector('.facts').getBoundingClientRect().top]")
        r.check(pos[0] < pos[1], f"[{size}] busca acima de Mais valioso")
        heads = await pg.evaluate("[...document.querySelectorAll('.sec-h h2')].map(h => h.textContent.trim())")
        r.eq(heads, ["Cômodos", "Cadastrados recentemente"], f"[{size}] seções: Categorias e Mais valiosos ficam em Mais > Gráficos")
        rows = await pg.evaluate("document.querySelectorAll('.sec .rows .rrow').length")
        r.check(rows >= 6, f"[{size}] cada cômodo com a sua parte do total ({rows})")
        r.check(await pg.evaluate(OVERFLOW), f"[{size}] sem rolagem para o lado")
        r.check(await pg.locator(".mic-top").count() == 1, f"[{size}] microfone do Falar no alto")
        await r.shot(pg, f"inicio-{size}-{scheme}", full_page=True)
        if size == "pc":
            await pg.wait_for_timeout(300)
            r.check(await pg.evaluate("document.activeElement && document.activeElement.dataset.input === 'home-q'") is False, "ao abrir o app, nada ganha o foco")
            await pg.click('.side a[href="#/buscar"]')
            await pg.wait_for_timeout(300)
            r.check(await pg.evaluate("document.activeElement && document.activeElement.matches('.sbar input')"), "no computador, ir para Buscar já põe o cursor na busca")
        await ctx.close()

    ctx, pg = await r.page(b, "cel", "dark")
    await r.open(pg, "#/", ".tag")
    await pg.fill('[data-input="home-q"]', "sofa")
    await pg.wait_for_timeout(500)
    r.check("#/buscar" in pg.url and "q=sofa" in pg.url, f"digitar no Início leva para Buscar ({pg.url.split('#')[1]})")
    await pg.wait_for_selector(".ssum")
    names = await pg.evaluate("[...document.querySelectorAll('#view .irow .nm')].map(e => e.textContent)")
    r.check(any("Sofá" in n for n in names), "sem acento acha com acento")
    r.check(await pg.locator("#view .irow mark").count() > 0, "o termo aparece destacado")
    await pg.fill(".sbar .q input", "geladeira inox")
    await pg.wait_for_timeout(400)
    names = await pg.evaluate("[...document.querySelectorAll('#view .irow .nm')].map(e => e.textContent)")
    r.eq(names, ["Geladeira frost free inox"], "várias palavras")
    await pg.fill(".sbar .q input", "")
    await pg.select_option('[data-input="search-room"]', "cozinha")
    await pg.wait_for_timeout(300)
    n = await pg.locator("#view .irow").count()
    r.eq(n, sum(1 for i in r.data()["items"] if i["room"] == "cozinha"), "filtro por cômodo")
    await pg.select_option('[data-input="search-cat"]', "eletronicos")
    await pg.wait_for_timeout(300)
    n = await pg.locator("#view .irow").count()
    r.eq(n, sum(1 for i in r.data()["items"] if i["room"] == "cozinha" and i["cat"] == "eletronicos"), "filtro por cômodo e categoria juntos")
    await pg.select_option('[data-input="search-room"]', "")
    await pg.select_option('[data-input="search-cat"]', "")
    await pg.select_option('[data-input="search-ord"]', "val")
    await pg.wait_for_timeout(300)
    vals = await pg.evaluate("[...document.querySelectorAll('#view .irow .val')].map(e => +e.textContent.replace(/[^0-9,]/g, '').replace(',', '.'))")
    r.check(vals[:10] == sorted(vals[:10], reverse=True), f"ordem por valor ({vals[:5]})")
    r.check("ord=val" in pg.url, "a busca fica no endereço (Voltar e compartilhar)")
    await pg.fill(".sbar .q input", "xyzinexistente")
    await pg.wait_for_timeout(400)
    r.check(await pg.locator("#view .empty").count() == 1, "sem resultado: aviso")
    await r.shot(pg, "busca-vazia")
    await pg.goto(r.base + "#/buscar?q=livros&cat=livros")
    await pg.wait_for_selector(".ssum")
    r.eq(await pg.input_value('[data-input="search-cat"]'), "livros", "abrir a busca pelo endereço já aplica os filtros")
    await r.shot(pg, "busca")
    await ctx.close()
    await b.close()


main("inicio_busca", body)
