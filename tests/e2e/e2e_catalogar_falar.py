"""Catalogar foto com IA (enviar, ler, revisar, adicionar, guardar a foto no cômodo, Outra foto) e Falar (microfone de mentira); com a IA desligada, o Falar some."""
import os

from e2e_lib import OVERFLOW, helpers, main

SPEECH = "Sofá cinza de três lugares, uns dois mil reais. Televisão Samsung de 55 polegadas, três mil. E duas luminárias de chão."


async def body(r, p):
    r.start(search=False)
    foto = os.path.join(helpers.FIXTURE, "photos", "escritorio-1.jpg")
    b = await r.browser(p, mic=True)

    # -- Catalogar, no computador (envia arquivo)
    ctx, pg = await r.page(b, "pc", "light", accent="azul")
    await r.open(pg, "#/c/escritorio", ".rhead")
    room_photos = len(next(x for x in r.data()["rooms"] if x["id"] == "escritorio")["photos"])
    n_items = len(r.data()["items"])
    await pg.click('.rhead-actions [data-act="catalog"]')
    await pg.wait_for_selector('[data-ct="upload"]')
    r.check(await pg.is_disabled('[data-ct="read"]'), "Ler foto desligado até escolher a foto")
    r.eq(await pg.input_value("#c-room"), "escritorio", "o cômodo de onde abriu já vem escolhido")
    async with pg.expect_file_chooser() as fc:
        await pg.click('[data-ct="upload"]')
    await (await fc.value).set_files(foto)
    await pg.wait_for_selector(".cat-photo img", timeout=10000)
    r.check(await pg.is_enabled('[data-ct="read"]'), "com a foto, Ler foto liga")
    await pg.fill("#c-hint", "itens da mesa")
    await r.shot(pg, "catalogar-pronto")
    await pg.click('[data-ct="read"]')
    await pg.wait_for_selector(".ai-wait", timeout=4000)
    r.check("Lendo a foto" in await pg.text_content(".ai-wait"), "Lendo a foto…")
    await pg.wait_for_selector(".found li", timeout=15000)
    r.eq(await pg.locator(".found li").count(), 3, "a IA (simulada) lista 3 objetos")
    r.check(await pg.locator(".found .pill", has_text="IA pouco segura").count() == 1, "item com pouca certeza vem marcado para conferir")
    r.eq((await pg.text_content('[data-ct="add"]')).strip(), "Adicionar 3 itens", "botão conta os itens marcados")
    await pg.uncheck('.fcheck[data-ri="1"]')
    r.eq((await pg.text_content('[data-ct="add"]')).strip(), "Adicionar 2 itens", "desmarcar tira da conta")
    await pg.fill('.fname[data-ri="0"]', "Luminária articulada")
    await pg.fill('[data-ri="0"][data-rf="value"]', "120")
    r.check(await pg.is_checked('[data-ct-in="keep"]'), "Guardar esta foto nas fotos do cômodo vem marcado")
    await r.shot(pg, "catalogar-revisar")
    # Outra foto volta sem perder o cômodo; ler de novo
    await pg.click('[data-ct="back"]')
    await pg.wait_for_selector('[data-ct="read"]')
    r.check(await pg.locator(".cat-photo img").count() == 1, "Outra foto volta com a foto escolhida")
    await pg.click('[data-ct="read"]')
    await pg.wait_for_selector(".found li", timeout=15000)
    await pg.uncheck('.fcheck[data-ri="1"]')
    await pg.fill('.fname[data-ri="0"]', "Luminária articulada")
    await pg.fill('[data-ri="0"][data-rf="value"]', "120")
    # descartar pergunta
    await pg.click('.dlg-h [data-ct="cancel"]')
    await pg.wait_for_selector('[data-r="0"]', timeout=4000)
    r.check("Descartar" in await pg.text_content("dialog.confirm, dialog:last-of-type"), "fechar com itens lidos pergunta antes")
    await pg.click('[data-r="0"]')
    await pg.wait_for_timeout(200)
    await pg.click('[data-ct="add"]')
    t = pg.locator(".toast", has_text="2 itens adicionados em Escritório")
    await t.wait_for(timeout=6000)
    d = r.data()
    new = [i for i in d["items"] if i["room"] == "escritorio" and i.get("source") == "ia"]
    r.eq(len(d["items"]), n_items + 2, "adiciona só os marcados")
    lum = next((i for i in new if i["name"] == "Luminária articulada"), None)
    r.check(lum is not None and lum["value"] == 120 and len(lum["photos"]) == 1, "com o nome e o valor mudados, e a foto")
    room = next(x for x in d["rooms"] if x["id"] == "escritorio")
    r.eq(len(room["photos"]), room_photos + 1, "a foto vai para as fotos do cômodo")
    r.eq(room["photos"][-1].get("label"), "itens da mesa", "a dica vira o rótulo da foto")
    await t.locator("button").click()
    await pg.wait_for_timeout(400)
    r.check("#/c/escritorio" in pg.url, "Ver leva ao cômodo")

    # foto do cômodo: não guarda de novo
    await pg.click('.rhead-actions [data-act="catalog"]')
    await pg.wait_for_selector('[data-ct="roomphoto"]')
    await pg.click('[data-ct="roomphoto"]')
    await pg.wait_for_selector(".pick label")
    picker = pg.locator("dialog", has=pg.locator(".pick"))
    await picker.locator(".pick label").first.click()
    await picker.locator("[data-ok]").click()
    await pg.wait_for_selector(".cat-photo img")
    await pg.click('[data-ct="read"]')
    await pg.wait_for_selector(".found li", timeout=15000)
    r.eq(await pg.locator('[data-ct-in="keep"]').count(), 0, "foto que já é do cômodo: sem Guardar esta foto")
    await pg.click('.dlg-f [data-ct="cancel"]')
    await pg.click('[data-r="1"]')
    await ctx.close()

    # -- Catalogar, celular estreito: o aviso de pouca certeza quebra dentro da borda
    ctx, pg = await r.page(b, "estreito", "dark", accent="coral")
    await r.open(pg, "#/c/quarto", ".rhead")
    await pg.click('.rhead-actions [data-act="catalog"]')
    await pg.wait_for_selector('[data-ct="upload"]')
    async with pg.expect_file_chooser() as fc:
        await pg.click('[data-ct="upload"]')
    await (await fc.value).set_files(foto)
    await pg.wait_for_selector(".cat-photo img", timeout=10000)
    await pg.click('[data-ct="read"]')
    await pg.wait_for_selector(".found li", timeout=15000)
    fits = await pg.evaluate("[...document.querySelectorAll('.found .pill')].every(e => e.getBoundingClientRect().right <= e.closest('li').getBoundingClientRect().right + 0.5)")
    r.check(fits, "aviso dentro da borda do item")
    r.check(await pg.evaluate(OVERFLOW), "sem rolagem para o lado")
    await pg.locator(".found .pill").first.scroll_into_view_if_needed()
    await r.shot(pg, "catalogar-estreito")
    await ctx.close()

    # -- Falar com IA (simulada)
    ctx, pg = await r.page(b, "cel", "dark", accent="lilas", perms=["microphone"])
    await r.open(pg, "#/", ".tag")
    await pg.click(".mic-top")
    await pg.wait_for_selector(".voice.on", timeout=8000)
    r.check(True, "o microfone abre e já ouve")
    await pg.wait_for_timeout(900)
    r.check(await pg.is_enabled('[data-ct="done"]'), "Pronto liga enquanto ouve")
    await r.shot(pg, "falar-ouvindo")
    await pg.click('[data-ct="done"]')
    await pg.wait_for_selector(".found li", timeout=15000)
    r.eq((await pg.text_content(".heard span")).strip(), f"“{SPEECH}”", "mostra o que ouviu")
    names = await pg.evaluate("[...document.querySelectorAll('.found .fname')].map(i => i.value)")
    r.eq(names, ["Sofá cinza de três lugares", "Televisão Samsung 55 polegadas", "Luminária de chão"], "a IA separa os itens")
    await pg.select_option('.found ~ * #c-room, #c-room', "sala")
    await pg.wait_for_timeout(200)
    await r.shot(pg, "falar-revisar")
    await pg.click('[data-ct="add"]')
    await pg.locator(".toast", has_text="3 itens adicionados em Sala de estar").wait_for(timeout=6000)
    voz = [i for i in r.data()["items"] if i.get("source") == "voz"]
    r.check(len(voz) == 3 and all(i["room"] == "sala" for i in voz) and all(not i["photos"] for i in voz), "itens falados vão para o cômodo escolhido, sem foto")
    # Falar de novo
    await pg.click(".mic-top")
    await pg.wait_for_selector(".voice.on", timeout=8000)
    await pg.wait_for_timeout(700)
    await pg.click('[data-ct="done"]')
    await pg.wait_for_selector(".found li", timeout=15000)
    await pg.click('[data-ct="back"]')
    await pg.wait_for_selector(".voice.on", timeout=8000)
    r.check(True, "Falar de novo volta a ouvir")
    await pg.click('.dlg-f [data-ct="cancel"]')
    await pg.wait_for_timeout(300)
    r.eq(await pg.locator("dialog[open]").count(), 0, "Cancelar enquanto ouve fecha sem perguntar")
    await ctx.close()

    # -- IA desligada: o Falar some junto (sem o microfone no alto); Adicionar vai direto para o item
    r.api("PUT", "api/settings", {"ai": False})
    ctx, pg = await r.page(b, "cel", "light", accent="verde", perms=["microphone"])
    await r.open(pg, "#/", ".tag")
    r.eq(await pg.locator('[data-act="catalog"]').count(), 0, "IA desligada: sem Catalogar")
    r.eq(await pg.locator(".mic-top, .chat-top").count(), 0, "IA desligada: sem o microfone e sem Conversar no alto")
    await pg.click(".tabbar .plus")
    await pg.wait_for_selector("dialog.modal .form", timeout=4000)
    r.eq(await pg.locator("[data-go]").count(), 0, "Adicionar abre o item direto, sem um menu de uma linha só")
    r.check("Novo item" in await pg.text_content("dialog.modal h2"), "o item novo")
    await r.shot(pg, "adicionar-sem-ia")
    await pg.click('dialog.modal .dlg-h [data-ed="cancel"]')
    await pg.wait_for_timeout(300)
    r.api("PUT", "api/settings", {"ai": True})
    await ctx.close()

    # -- sem permissão do microfone: diz o que fazer
    ctx, pg = await r.page(b, "cel", "dark", init="navigator.mediaDevices.getUserMedia = () => Promise.reject(Object.assign(new Error('x'), {name: 'NotAllowedError'}));")
    await r.open(pg, "#/", ".tag")
    await pg.click(".mic-top")
    await pg.wait_for_selector("dialog .formerr", timeout=8000)
    msg = (await pg.text_content("dialog .formerr")).strip()
    r.check("microfone" in msg.lower(), f"microfone bloqueado: explica ({msg})")
    await r.shot(pg, "falar-sem-permissao")
    await ctx.close()
    await b.close()


main("catalogar_falar", body)
